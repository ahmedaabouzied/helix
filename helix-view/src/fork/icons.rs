#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_for_binary_search() {
        for (label, table) in [("BY_NAME", BY_NAME), ("BY_EXTENSION", BY_EXTENSION)] {
            assert!(
                table.windows(2).all(|pair| pair[0].0 < pair[1].0),
                "{label} is out of order; lookup would silently miss entries"
            );
        }
    }

    #[test]
    fn extensions_resolve() {
        assert_eq!(
            for_file(Path::new("main.rs")),
            lookup(BY_EXTENSION, "rs").unwrap()
        );
        assert_eq!(
            for_file(Path::new("a/b/main.go")),
            lookup(BY_EXTENSION, "go").unwrap()
        );
    }

    #[test]
    fn whole_names_beat_extensions() {
        assert_ne!(
            for_file(Path::new("Dockerfile")),
            FILE,
            "an extensionless name resolves through the extension table"
        );
        assert_ne!(
            for_file(Path::new("Makefile")),
            FILE,
            "likewise for other whole-name keys"
        );
        assert_ne!(
            for_file(Path::new("vite.config.ts")),
            lookup(BY_EXTENSION, "ts").unwrap(),
            "the whole-name entry wins over the `ts` extension"
        );
    }

    #[test]
    fn unknown_and_extensionless_files_fall_back() {
        assert_eq!(for_file(Path::new("nope.zzzz")), FILE);
        assert_eq!(for_file(Path::new("LICENCE-XYZ")), FILE);
    }

    #[test]
    fn extension_case_is_folded_as_a_second_try() {
        assert_eq!(for_file(Path::new("A.RS")), for_file(Path::new("a.rs")));
    }

    #[test]
    fn a_document_without_a_path_gets_the_fallback() {
        assert_eq!(for_document(None), FILE);
        assert_eq!(
            for_document(Some(Path::new("main.rs"))),
            for_file(Path::new("main.rs"))
        );
    }

    #[test]
    fn directories_open_and_shut() {
        assert_eq!(for_directory(false), DIRECTORY);
        assert_eq!(for_directory(true), DIRECTORY_OPEN);
        assert_ne!(DIRECTORY, DIRECTORY_OPEN);
    }
}
