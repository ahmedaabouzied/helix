//! File-type icons.
//!
//! Lives in `helix-view` rather than beside its first caller so that anything
//! rendering a path can use it — the file tree today, a statusline or
//! bufferline later.
//!
//! Generated from nvim-web-devicons' `icons_by_file_extension` and
//! `icons_by_filename` tables, so the glyphs and colours match the Neovim setup
//! this fork's theme was ported from. Regenerate by re-parsing those Lua tables
//! if the plugin is updated; nothing here is meant to be hand-edited.
//!
//! Both tables are sorted by key so lookup is a binary search with no
//! allocation and no startup cost. A test guards that ordering, because a
//! hand-edit that broke it would not fail loudly — it would just start missing
//! icons.
//!
//! The glyphs need a Nerd Font. Without one they render as tofu.

use crate::graphics::Color;
use std::path::Path;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Icon {
    pub glyph: &'static str,
    pub color: Color,
}

impl Icon {
    const fn new(glyph: &'static str, r: u8, g: u8, b: u8) -> Self {
        Self {
            glyph,
            color: Color::Rgb(r, g, b),
        }
    }
}

/// Shown for a file with no entry in either table.
pub const FILE: Icon = Icon::new("\u{f15b}", 0x9e, 0xa7, 0xb3);
/// devicons has no folder glyphs — those come from nvim-tree — so these are the
/// conventional Nerd Font pair.
pub const DIRECTORY: Icon = Icon::new("\u{f07b}", 0x82, 0xaa, 0xff);
pub const DIRECTORY_OPEN: Icon = Icon::new("\u{f07c}", 0x82, 0xaa, 0xff);

/// The icon for a file, by exact name first and extension second — the order
/// nvim-web-devicons uses, so that `vite.config.ts` beats plain `ts`.
pub fn for_file(path: &Path) -> Icon {
    let name = path.file_name().and_then(|name| name.to_str());

    if let Some(name) = name {
        if let Some(icon) = lookup(BY_NAME, name) {
            return icon;
        }
    }

    // Extensionless names such as `Dockerfile` and `Makefile` are stored in the
    // extension table under their whole name, which is how devicons keys them.
    let Some(key) = path.extension().and_then(|ext| ext.to_str()).or(name) else {
        return FILE;
    };

    // Keys are mostly lowercase but not all — `R` is its own entry — so try as
    // written before folding case.
    lookup(BY_EXTENSION, key)
        .or_else(|| lookup(BY_EXTENSION, &key.to_lowercase()))
        .unwrap_or(FILE)
}

/// The icon for a document, which may be a scratch buffer with no path yet.
///
/// Exists so callers that hold an `Option<&Path>` — the statusline does — carry
/// no icon logic of their own.
pub fn for_document(path: Option<&Path>) -> Icon {
    path.map_or(FILE, for_file)
}

pub fn for_directory(expanded: bool) -> Icon {
    if expanded {
        DIRECTORY_OPEN
    } else {
        DIRECTORY
    }
}

fn lookup(table: &[(&str, Icon)], key: &str) -> Option<Icon> {
    table
        .binary_search_by_key(&key, |(key, _)| key)
        .ok()
        .map(|index| table[index].1)
}

